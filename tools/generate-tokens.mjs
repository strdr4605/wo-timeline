#!/usr/bin/env node
// Writes src/styles/_tokens.scss from docs/design/tokens.json.
// The token file is the single source of truth: no colour, size or radius is written twice.
//
// Usage: node tools/generate-tokens.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'docs/design/tokens.json'), 'utf8'));

// The font files and the CDN url are assets, not style values.
const SKIP = new Set(['typography.fontFiles', 'typography.cdn']);

// The token file names the font, not its CSS weight. Circular Std ships these weights.
const FONT_WEIGHT = { book: 400, regular: 400, medium: 500, bold: 700 };

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const nameFor = (path) => {
  const [group, ...rest] = path;
  const tail = rest.filter((p) => p !== 'styles').map(kebab);
  if (group === 'colors') return ['color', ...tail].join('-');
  if (group === 'typography') {
    if (path[1] === 'fontFamily') return 'font-family';
    return ['type', ...tail].join('-');
  }
  if (group === 'radii') return ['radius', ...tail].join('-');
  if (group === 'layout') return ['layout', ...tail].join('-');
  return ['component', ...tail].join('-');
};

const valueFor = (value, path) => {
  const key = path[path.length - 1];
  if (typeof value === 'number') {
    if (/alpha/i.test(key)) return String(value);
    return `${value}px`;
  }
  // Hex colours stay unquoted so Sass emits a valid CSS colour.
  if (value.startsWith('#')) return value;
  return `"${value}"`;
};

const rows = [];

const walk = (value, path) => {
  if (SKIP.has(path.join('.'))) return;
  if (value && typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) walk(child, [...path, key]);
    return;
  }
  rows.push({ name: nameFor(path), value: valueFor(value, path) });
  if (path[0] === 'typography' && path[path.length - 1] === 'font') {
    const weight = FONT_WEIGHT[String(value).toLowerCase()];
    if (weight) rows.push({ name: `${nameFor(path)}-weight`, value: String(weight) });
  }
};

walk(tokens.colors, ['colors']);
walk(tokens.typography, ['typography']);
walk(tokens.radii, ['radii']);
walk(tokens.layout, ['layout']);
walk(tokens.components, ['components']);

const header = [
  '// Generated by tools/generate-tokens.mjs from docs/design/tokens.json.',
  '// Do not edit by hand: run `npm run tokens` after the token file changes.',
  '',
].join('\n');

const body = rows.map((r) => `$${r.name}: ${r.value};`).join('\n');
writeFileSync(join(root, 'src/styles/_tokens.scss'), `${header}${body}\n`);
console.log(`wrote ${rows.length} token variables to src/styles/_tokens.scss`);
