import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1024 } });
await p.goto('http://localhost:4200/', { waitUntil: 'networkidle' });
await p.locator('.grid-row').nth(2).hover();
await p.waitForTimeout(200);
await p.screenshot({ path: '/tmp/wo-shots/row-hover.png' });
await p.locator('.work-center-row').nth(2).hover();
await p.waitForTimeout(200);
await p.screenshot({ path: '/tmp/wo-shots/rail-hover.png' });
await b.close();
